#!/usr/bin/env node
/* Builds the theme's page-transition files from src/motion-tokens.json, so the theme and the
   Remotion compositions share one set of values. Nothing in the outputs is typed by hand.
     snippets/pd-transition.liquid  part 'head': inline arrival CSS + the tiny flag script
                                    (default):   the panel markup (aria-hidden, SVG only)
     assets/pd-transition.css       page-1 "In" styles, loaded without blocking render
     assets/pd-transition.js        behaviour (deferred)
   Usage: node scripts/build-theme.mjs [--check]   (--check: fail if the outputs are stale) */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const project = path.resolve(here, '..');
const theme = path.resolve(project, '../prodani');
const tok = JSON.parse(fs.readFileSync(path.join(project, 'src/motion-tokens.json'), 'utf8'));

const T = tok.tempo.T;
const r = tok.rise;
const ms = (x) => Math.round(x * 1000) / 1000;
const IN = ms(r.in.share * T), HOLD = ms(r.hold.share * T), OUT = ms(r.out.share * T);
const DROP_DELAY = ms(r.stopDrop.startInHold * HOLD), DROP = ms(r.stopDrop.durationInHold * HOLD);
const bz = (e) => `cubic-bezier(${e.join(',')})`;
const { colors: c, logo: L, slow: S, guards: G, panel: P, loader: LD } = tok;
const LN = LD.line, LINE_W = LN.advance + LN.gap + LN.stop;
/* band padding as a share of the line's drawn width: bandPadEm of the line's em height */
/* the stop's drop, in line units: the Rise's drop scaled from the logo's stop to this one (as heat.tsx dropY) */
/* flow (tweaks 8): the panel rises with a curved leading edge; on arrival the line plays the
   logo's hop (letters ripple, the stop jumps, turns and squashes); the panel fades out in place. */
const F = LD.flow, CURVE = F.curveVh, RP = F.ripple, ST = F.stop;
const LINE_DROP = Math.round(r.stopDrop.fromY * (LN.stop / L.stop.w));
const BAND_PAD = Math.round((LD.bandPadEm * 1000 / LINE_W) * 10000) / 10000;
const GEN = 'GENERATED by theme/prodani-motion/scripts/build-theme.mjs from src/motion-tokens.json. Do not edit here.';

/* ---- Arrival CSS: inline in <head>, so the panel covers at first paint without a
   render-blocking request. Default state = panel hidden, content untouched. ---- */
const css = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').replace(/ ?([{}:;,>]) ?/g, '$1').replace(/;}/g, '}').trim();
const inlineCss = css(`
.pd-tr{position:fixed;top:0;left:0;width:100%;height:100%;z-index:2147483600;pointer-events:none;visibility:hidden;overflow:hidden}
.pd-tr__panel{position:absolute;top:0;left:0;width:100%;height:100%;background:${c.ink};display:flex;align-items:center;justify-content:center;transform:translate3d(0,100%,0)}
.pd-tr__band{position:relative;z-index:1;width:100%;display:flex;justify-content:center;background:${c.ink};padding:calc(min(${LD.lineWidthVw}vw,${LD.lineMaxPx}px) * ${BAND_PAD}) 0}
.pd-tr__line{display:block;width:min(${LD.lineWidthVw}vw,${LD.lineMaxPx}px);height:auto;overflow:visible}
.pd-tr__word{fill:${c.white};transform-box:fill-box;transform-origin:50% 100%}
.pd-tr__stop{fill:${c.pink};transform-box:fill-box;transform-origin:50% 50%}
@media (prefers-reduced-motion:no-preference){
/* Hard cap: whatever happens to the JS, the panel is gone ${G.capMs}ms after it appeared. */
html.pd-tr-arrive .pd-tr,html.pd-tr-leave .pd-tr{visibility:visible;animation:pd-tr-cap 1ms linear ${G.capMs}ms forwards}
@keyframes pd-tr-cap{to{visibility:hidden;opacity:0}}
html.pd-tr-arrive .pd-tr__panel{transform:none}
/* Arrival: the logo's hop. The letters ripple left to right; the stop jumps, turns half a turn in the air and lands with a squash. */
html.pd-tr-arrive .pd-tr__word{animation:pd-tr-ripple ${RP.ms}ms cubic-bezier(.33,1,.68,1) calc(var(--i) * ${RP.stepMs}ms) both}
@keyframes pd-tr-ripple{40%{transform:translateY(-${RP.liftPct}%)}}
html.pd-tr-arrive .pd-tr__stop{animation:pd-tr-jump ${ST.ms}ms linear ${ST.delayMs}ms both}
@keyframes pd-tr-jump{0%{transform:none;animation-timing-function:cubic-bezier(.2,.7,.3,1)}12%{transform:translateY(8%) scale(1.12,.84);animation-timing-function:cubic-bezier(.2,.7,.3,1)}48%{transform:translateY(-190%) rotate(180deg);animation-timing-function:cubic-bezier(.6,0,.9,.5)}78%{transform:translateY(11%) rotate(180deg) scale(1.2,.78);animation-timing-function:cubic-bezier(.3,.7,.4,1)}90%{transform:translateY(-14%) rotate(180deg) scale(.96,1.04)}100%{transform:rotate(180deg)}}
/* Out: the panel fades away where it is. */
html.pd-tr-out .pd-tr__panel{animation:pd-tr-fade ${F.fadeMs}ms ease-out forwards}
@keyframes pd-tr-fade{to{opacity:0}}
}`);

/* ---- Page 1 "In": only needed after a click, so it loads async. ---- */
const leaveCss = `/* ${GEN} */
@media (prefers-reduced-motion: no-preference) {
  html.pd-tr-leave .pd-tr__panel { animation: pd-tr-in ${IN}ms ${bz(r.in.easing)} forwards; }
  /* the line rides up with the panel, still; it plays the logo's hop on page 2 */
  @keyframes pd-tr-in { from { transform: translate3d(0, 100%, 0); border-top-left-radius: 50% ${CURVE}vh; border-top-right-radius: 50% ${CURVE}vh; } to { transform: none; border-radius: 0; } }
}
`;

/* ---- <head> flag script (must stay under 300 bytes). ---- */
const headJs = `<script>try{var s=sessionStorage,k='${G.flagKey}',t=s.getItem(k);s.removeItem(k);if(t&&Date.now()-t<${G.flagMaxAgeMs}&&matchMedia('(prefers-reduced-motion:no-preference)').matches)document.documentElement.classList.add('pd-tr-arrive')}catch(e){}</script>`;

const snippet = `{%- comment -%} ${GEN}
  Page transition with HEAT AND EAT. (tweaks 8: the logo's hop on arrival, fade out). Rendered twice from layout/theme.liquid:
  part 'head' in <head> (inline arrival CSS + flag script), default right after <body> (the panel).
  The panel is hidden by default and only shows after a real click (page 1) or a fresh
  sessionStorage flag (page 2). Content is never hidden. Skipped in the theme editor. {%- endcomment -%}
{%- unless request.design_mode -%}
{%- if part == 'head' -%}
<style>${inlineCss}</style>
${headJs}
<link rel="stylesheet" href="{{ 'pd-transition.css' | asset_url }}" media="print" onload="this.media='all'">
<script src="{{ 'pd-transition.js' | asset_url }}" defer="defer"></script>
{%- else -%}
<div class="pd-tr" aria-hidden="true"><div class="pd-tr__panel"><div class="pd-tr__band"><svg class="pd-tr__line" viewBox="0 ${LN.top} ${LINE_W} ${-LN.top}" focusable="false" xmlns="http://www.w3.org/2000/svg">${LN.glyphs.map((d, i) => `<path class="pd-tr__word" style="--i:${i}" d="${d}"/>`).join('')}<rect class="pd-tr__stop" x="${LN.advance + LN.gap}" y="${-LN.stop}" width="${LN.stop}" height="${LN.stop}"/></svg></div></div></div>
{%- endif -%}
{%- endunless -%}
`;

const config = {
  in: IN, holdEnd: F.holdMs, out: F.fadeMs, cap: G.capMs, fallback: G.navFallbackMs, key: G.flagKey,
};
const js = fs.readFileSync(path.join(project, 'theme-src/pd-transition.js'), 'utf8').replace('__CONFIG__', JSON.stringify(config));

const outputs = {
  'snippets/pd-transition.liquid': snippet,
  'assets/pd-transition.css': leaveCss,
  'assets/pd-transition.js': js,
};

/* ---- Budgets from the brief ---- */
const headBytes = Buffer.byteLength(headJs);
const jsGzip = zlib.gzipSync(js, { level: 9 }).length;
const problems = [];
if (headBytes >= 300) problems.push(`inline head script is ${headBytes} B (limit 300)`);
if (jsGzip >= 3072) problems.push(`pd-transition.js is ${jsGzip} B gzipped (limit 3072)`);

const check = process.argv.includes('--check');
for (const [rel, body] of Object.entries(outputs)) {
  const file = path.join(theme, rel);
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (check) { if (cur !== body) problems.push(`${rel} is stale: run npm run build:theme`); }
  else if (cur !== body) fs.writeFileSync(file, body);
}
console.log(`head script ${headBytes} B · js ${Buffer.byteLength(js)} B (${jsGzip} B gzip) · inline css ${Buffer.byteLength(inlineCss)} B`);
console.log(`loader: in ${IN} · hold ${F.holdMs} (ripple ${RP.ms}+${RP.stepMs}/letter, stop ${ST.delayMs}+${ST.ms}) · fade ${F.fadeMs}`);
if (problems.length) { console.error('FAIL\n- ' + problems.join('\n- ')); process.exit(1); }
console.log(check ? 'theme files are up to date' : 'wrote ' + Object.keys(outputs).join(', '));
